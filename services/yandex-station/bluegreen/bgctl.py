#!/usr/bin/env python3
"""bgctl: state, switch and health helpers for the blue/green voice stack.

State lives outside the code directory (AISIS_BG_STATE, default
~/.local/share/aisis/bluegreen-state):

  state.env                 PROD_ACTIVE, PROD_IMG_BLUE/GREEN, STAGE_* (compose env file)
  <env>/switch/nginx.conf   static switch config (generated)
  <env>/switch/active.conf  upstreams: active color is primary, the other `backup`

The switch (nginx, host network) owns the canonical ports. nginx fails over by
itself on refused or timed-out connects (`max_fails`, `backup`); this tool and
failover.py additionally move the primary role, so a hung-but-listening color
is replaced too. A flip is an `nginx -s reload`; `worker_shutdown_timeout`
bounds how long old connections (the speaker's WebSocket) stay on the old color.

Commands: init, status, health, wait, devices, flip, render, set-image, get, compose, smoke.
"""
from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
import tempfile
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import smoke  # noqa: E402

CODE_DIR = Path(__file__).resolve().parent
HOME = Path.home()
STATE_DIR = Path(os.environ.get("AISIS_BG_STATE", HOME / ".local/share/aisis/bluegreen-state"))
RUNTIME_ENV = Path(os.environ.get("AISIS_RUNTIME_ENV", HOME / ".config/aisis/runtime.env"))
COMPOSE_FILE = CODE_DIR / "compose.bluegreen.yaml"
COMPOSE_PROJECT = "aisis-voice"
STATE_FILE = STATE_DIR / "state.env"
COLORS = ("blue", "green")

# (uniproxy, api, function-state) per role; keep in sync with compose.bluegreen.yaml.
ENVS = {
    "prod": {
        "switch": (31115, 31116, 31114),
        "blue": (31215, 31216, 31214),
        "green": (31315, 31316, 31314),
        "status_port": 31113,
        "bind": ("0.0.0.0", "127.0.0.1", "0.0.0.0"),
        "switch_container": "aisis-switch-prod",
    },
    "stage": {
        "switch": (31415, 31416, 31414),
        "blue": (31515, 31516, 31514),
        "green": (31615, 31616, 31614),
        "status_port": 31413,
        "bind": ("127.0.0.1", "127.0.0.1", "127.0.0.1"),
        "switch_container": "aisis-switch-stage",
    },
}


def other(color: str) -> str:
    return "green" if color == "blue" else "blue"


def container(env: str, color: str) -> str:
    return f"aisis-quasar-{env}-{color}"


def service(env: str, color: str) -> str:
    return f"quasar-{env}-{color}"


# ── state ────────────────────────────────────────────────────────────────

def load_state() -> dict[str, str]:
    state: dict[str, str] = {}
    if STATE_FILE.exists():
        for line in STATE_FILE.read_text().splitlines():
            if "=" in line and not line.lstrip().startswith("#"):
                key, _, value = line.partition("=")
                state[key.strip()] = value.strip()
    return state


def _atomic_write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=path.name + ".")
    with os.fdopen(fd, "w") as handle:
        handle.write(text)
    os.chmod(tmp, 0o644)
    os.replace(tmp, path)


def save_state(state: dict[str, str]) -> None:
    _atomic_write(STATE_FILE, "".join(f"{k}={v}\n" for k, v in sorted(state.items())))


def active_color(env: str) -> str:
    color = load_state().get(f"{env.upper()}_ACTIVE", "blue")
    if color not in COLORS:
        raise SystemExit(f"bad {env} active color in state: {color!r}")
    return color


# ── switch config ────────────────────────────────────────────────────────

def _nginx_conf(env: str) -> str:
    cfg = ENVS[env]
    (uni, api, fn), (b_uni, b_api, b_fn) = cfg["switch"], cfg["bind"]
    return f"""# generated by bgctl.py: do not edit
worker_processes 1;
# Bound how long connections opened before a reload keep using the old color.
worker_shutdown_timeout 5s;
error_log /dev/stderr warn;
pid /tmp/switch.pid;
events {{ worker_connections 1024; }}
http {{
    access_log off;
    map $http_upgrade $connection_upgrade {{ default upgrade; '' close; }}
    include /etc/nginx/switch/active.conf;
    proxy_http_version 1.1;
    proxy_set_header Host $http_host;
    proxy_set_header Upgrade $http_upgrade;
    proxy_set_header Connection $connection_upgrade;
    proxy_set_header X-Real-IP $remote_addr;
    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
    proxy_connect_timeout 2s;
    proxy_read_timeout 3600s;
    proxy_send_timeout 3600s;
    proxy_buffering off;
    proxy_request_buffering off;
    proxy_next_upstream error timeout;
    proxy_next_upstream_tries 2;
    client_max_body_size 20m;
    server {{ listen {b_uni}:{uni}; location / {{ proxy_pass http://q_uni; }} }}
    server {{ listen {b_api}:{api}; location / {{ proxy_pass http://q_api; }} }}
    server {{ listen {b_fn}:{fn}; location / {{ proxy_pass http://q_fn; }} }}
}}
"""


def _active_conf(env: str, color: str) -> str:
    cfg = ENVS[env]
    lines = [f"# generated by bgctl.py: active={color}"]
    for index, name in enumerate(("uni", "api", "fn")):
        primary, standby = cfg[color][index], cfg[other(color)][index]
        lines.append(
            f"upstream q_{name} {{ server 127.0.0.1:{primary} max_fails=1 fail_timeout=2s; "
            f"server 127.0.0.1:{standby} backup; }}"
        )
    lines.append(
        f"server {{ listen 127.0.0.1:{cfg['status_port']}; location / {{ return 200 \"{color}\\n\"; }} }}"
    )
    return "\n".join(lines) + "\n"


def render(env: str) -> None:
    switch_dir = STATE_DIR / env / "switch"
    _atomic_write(switch_dir / "nginx.conf", _nginx_conf(env))
    _atomic_write(switch_dir / "active.conf", _active_conf(env, active_color(env)))


def _docker(*args: str, timeout: float = 30.0) -> subprocess.CompletedProcess:
    return subprocess.run(["docker", *args], capture_output=True, text=True, timeout=timeout)


def container_running(name: str) -> bool:
    result = _docker("inspect", "-f", "{{.State.Running}}", name, timeout=10)
    return result.returncode == 0 and result.stdout.strip() == "true"


def reload_switch(env: str) -> tuple[bool, str]:
    name = ENVS[env]["switch_container"]
    if not container_running(name):
        return False, f"{name} is not running"
    conf = "/etc/nginx/switch/nginx.conf"
    test = _docker("exec", name, "nginx", "-t", "-c", conf, timeout=15)
    if test.returncode != 0:
        return False, f"nginx -t failed: {test.stderr.strip()[-300:]}"
    reload = _docker("exec", name, "nginx", "-c", conf, "-s", "reload", timeout=15)
    if reload.returncode != 0:
        return False, f"reload failed: {reload.stderr.strip()[-300:]}"
    return True, "reloaded"


def flip(env: str, color: str | None = None) -> tuple[str, str, float]:
    """Make `color` (default: the other one) primary. Returns (old, new, seconds)."""
    started = time.monotonic()
    old = active_color(env)
    new = color or other(old)
    state = load_state()
    state[f"{env.upper()}_ACTIVE"] = new
    save_state(state)
    render(env)
    ok, detail = reload_switch(env)
    if not ok:
        state[f"{env.upper()}_ACTIVE"] = old
        save_state(state)
        render(env)
        raise RuntimeError(f"flip {old}->{new} aborted: {detail}")
    return old, new, time.monotonic() - started


# ── health ───────────────────────────────────────────────────────────────

def health(env: str, color: str, timeout: float = 1.5) -> dict:
    uni, api, _ = ENVS[env][color]
    api_ok = smoke.http_status(f"http://127.0.0.1:{api}/devices", timeout) == 200
    # Skip the second probe when the first already failed: a hung process would
    # otherwise cost two timeouts per tick and slow failure detection.
    uni_ok = api_ok and smoke.http_status(f"http://127.0.0.1:{uni}/", timeout) > 0
    return {"ok": uni_ok, "api": api_ok, "uniproxy": uni_ok}


def switch_health(env: str, timeout: float = 2.0) -> dict:
    uni, api, _ = ENVS[env]["switch"]
    api_ok = smoke.http_status(f"http://127.0.0.1:{api}/devices", timeout) == 200
    # Skip the second probe when the first already failed: a hung process would
    # otherwise cost two timeouts per tick and slow failure detection.
    uni_ok = api_ok and smoke.http_status(f"http://127.0.0.1:{uni}/", timeout) > 0
    return {"ok": uni_ok, "api": api_ok, "uniproxy": uni_ok}


def connected_devices(env: str, timeout: float = 3.0) -> list[str]:
    """DUIDs with a live WebSocket on the active color (queried through the switch)."""
    devices = smoke.http_json(f"http://127.0.0.1:{ENVS[env]['switch'][1]}/devices", timeout)
    return [d["duid"] for d in devices or [] if d.get("connected")]


def wait_healthy(env: str, color: str, seconds: float) -> bool:
    deadline = time.monotonic() + seconds
    while time.monotonic() < deadline:
        if health(env, color)["ok"]:
            return True
        time.sleep(1)
    return False


# ── compose ──────────────────────────────────────────────────────────────

def compose_cmd(env: str | None, *args: str) -> list[str]:
    cmd = ["docker", "compose", "-p", COMPOSE_PROJECT, "-f", str(COMPOSE_FILE)]
    if RUNTIME_ENV.exists():
        cmd += ["--env-file", str(RUNTIME_ENV)]
    cmd += ["--env-file", str(STATE_FILE)]
    if env:
        cmd += ["--profile", env]
    return cmd + list(args)


def run_compose(env: str | None, *args: str, check: bool = True) -> int:
    child_env = {**os.environ, "BG_STATE": str(STATE_DIR)}
    return subprocess.run(compose_cmd(env, *args), env=child_env, check=check).returncode


# ── CLI ──────────────────────────────────────────────────────────────────

def cmd_init(args: argparse.Namespace) -> int:
    state = load_state()
    for env in ENVS:
        state.setdefault(f"{env.upper()}_ACTIVE", "blue")
        for color in COLORS:
            state[f"{env.upper()}_IMG_{color.upper()}"] = args.image if args.force else state.get(
                f"{env.upper()}_IMG_{color.upper()}", args.image)
    save_state(state)
    for env in ENVS:
        render(env)
    print(f"state: {STATE_FILE}")
    return 0


def cmd_status(args: argparse.Namespace) -> int:
    state = load_state()
    envs = [args.env] if args.env else list(ENVS)
    report = {}
    for env in envs:
        report[env] = {
            "active": active_color(env),
            "switch_container_running": container_running(ENVS[env]["switch_container"]),
            "switch": switch_health(env),
            "colors": {
                color: {
                    "image": state.get(f"{env.upper()}_IMG_{color.upper()}"),
                    "running": container_running(container(env, color)),
                    **health(env, color),
                }
                for color in COLORS
            },
        }
    print(json.dumps(report, indent=2, ensure_ascii=False))
    return 0


def cmd_health(args: argparse.Namespace) -> int:
    result = health(args.env, args.color)
    print(json.dumps(result))
    return 0 if result["ok"] else 1


def cmd_flip(args: argparse.Namespace) -> int:
    old, new, took = flip(args.env, args.color)
    print(json.dumps({"env": args.env, "from": old, "to": new, "seconds": round(took, 3)}))
    return 0


def cmd_render(args: argparse.Namespace) -> int:
    render(args.env)
    return 0


def cmd_set_image(args: argparse.Namespace) -> int:
    state = load_state()
    state[f"{args.env.upper()}_IMG_{args.color.upper()}"] = args.image
    save_state(state)
    return 0


def cmd_get(args: argparse.Namespace) -> int:
    if args.key == "active":
        print(active_color(args.env))
    elif args.key == "standby":
        print(other(active_color(args.env)))
    else:
        print(load_state().get(f"{args.env.upper()}_{args.key.upper()}", ""))
    return 0


def cmd_devices(args: argparse.Namespace) -> int:
    print("\n".join(connected_devices(args.env)))
    return 0


def cmd_wait(args: argparse.Namespace) -> int:
    return 0 if wait_healthy(args.env, args.color, args.seconds) else 1


def cmd_compose(args: argparse.Namespace) -> int:
    return run_compose(args.env, *args.rest, check=False)


def cmd_smoke(args: argparse.Namespace) -> int:
    cfg = ENVS[args.env]
    target = cfg[args.target]
    result = smoke.run(f"http://127.0.0.1:{target[1]}", f"127.0.0.1:{target[0]}")
    print(json.dumps(result, ensure_ascii=False))
    return 0 if result["ok"] else 1


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)

    p = sub.add_parser("init", help="create state with an initial image for every color")
    p.add_argument("image")
    p.add_argument("--force", action="store_true", help="overwrite images already in state")
    p.set_defaults(func=cmd_init)

    p = sub.add_parser("status")
    p.add_argument("env", nargs="?", choices=list(ENVS))
    p.set_defaults(func=cmd_status)

    p = sub.add_parser("health", help="exit 0 when the color answers API /devices 200 and its uniproxy port")
    p.add_argument("env", choices=list(ENVS))
    p.add_argument("color", choices=COLORS)
    p.set_defaults(func=cmd_health)

    p = sub.add_parser("flip", help="move the primary role (default: to the other color) and reload the switch")
    p.add_argument("env", choices=list(ENVS))
    p.add_argument("color", nargs="?", choices=COLORS)
    p.set_defaults(func=cmd_flip)

    p = sub.add_parser("render", help="regenerate switch config from state (no reload)")
    p.add_argument("env", choices=list(ENVS))
    p.set_defaults(func=cmd_render)

    p = sub.add_parser("set-image")
    p.add_argument("env", choices=list(ENVS))
    p.add_argument("color", choices=COLORS)
    p.add_argument("image")
    p.set_defaults(func=cmd_set_image)

    p = sub.add_parser("get", help="print active|standby|IMG_BLUE|IMG_GREEN for an env")
    p.add_argument("env", choices=list(ENVS))
    p.add_argument("key")
    p.set_defaults(func=cmd_get)

    p = sub.add_parser("devices", help="print DUIDs connected on the active color (via the switch)")
    p.add_argument("env", choices=list(ENVS))
    p.set_defaults(func=cmd_devices)

    p = sub.add_parser("wait", help="wait until a color is healthy; exit 1 on timeout")
    p.add_argument("env", choices=list(ENVS))
    p.add_argument("color", choices=COLORS)
    p.add_argument("seconds", type=float)
    p.set_defaults(func=cmd_wait)

    p = sub.add_parser("compose", help="docker compose with the project, env files and profile applied")
    p.add_argument("env", choices=list(ENVS))
    p.add_argument("rest", nargs=argparse.REMAINDER)
    p.set_defaults(func=cmd_compose)

    p = sub.add_parser("smoke", help="API /devices + synthetic uniproxy handshake against one color or the switch")
    p.add_argument("env", choices=list(ENVS))
    p.add_argument("target", choices=("switch", *COLORS))
    p.set_defaults(func=cmd_smoke)

    args = parser.parse_args()
    try:
        return args.func(args)
    except (RuntimeError, subprocess.SubprocessError) as exc:
        print(f"bgctl: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
