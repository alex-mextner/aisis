#!/usr/bin/env bash
# Test speaker/speaker-dns.sh against a fake speaker: a stub `adb shell` runs the commands against a temp directory
# standing in for the device (paths under /data and /etc are redirected), with stub dhcpcd/ifconfig/nslookup/ps/id.
# Synthetic values only.   bash test-speaker-dns.sh
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
lan=$(cd "$here/.." && pwd)
T=$(mktemp -d)
trap 'rm -rf "$T"' EXIT
fail=0
check() { if [ "$2" = "$3" ]; then echo "PASS $1"; else echo "FAIL $1: got [$2] want [$3]"; fail=1; fi; }

DEV=$T/dev
mkdir -p "$T/bin" "$DEV/data" "$DEV/etc" "$DEV/tmp"
export DEV STUB_BIN=$T/bin

cat > "$T/bin/adb" <<'SH'
#!/usr/bin/env bash
[ "$1" = connect ] && { echo "connected to $2"; exit 0; }
shift 2   # -s <device>
[ "$1" = get-state ] && { echo device; exit 0; }
shift     # shell
cmd=$*
cmd=${cmd//\/data\//$DEV/data/}
cmd=${cmd//\/etc\//$DEV/etc/}
PATH=$STUB_BIN/dev:$PATH bash -c "$cmd" | sed "s|$DEV||g"
SH
mkdir -p "$T/bin/dev"
cat > "$T/bin/dev/id" <<'SH'
#!/usr/bin/env bash
[ "$1" = -u ] && echo 0
SH
cat > "$T/bin/dev/ps" <<'SH'
#!/usr/bin/env bash
echo "  1281 dhcpcd   dhcpcd: [manager] [ip4] [ip6]"
SH
cat > "$T/bin/dev/ifconfig" <<'SH'
#!/usr/bin/env bash
printf 'wlan0     Link encap:Ethernet  HWaddr 02:00:00:00:00:30\n          inet addr:192.0.2.30  Bcast:192.0.2.255  Mask:255.255.255.0\n'
SH
cat > "$T/bin/dev/nslookup" <<'SH'
#!/usr/bin/env bash
printf 'Server:    %s\nAddress:   %s:53\n\nName:      %s\nAddress:   %s\n' "$2" "$2" "$1" "${CANARY_ANSWER:-192.0.2.10}"
SH
cat > "$T/bin/dev/dhcpcd" <<'SH'
#!/usr/bin/env bash
case "$1" in
  -U) printf 'ip_address=192.0.2.30\ndomain_name_servers=192.0.2.10\ndhcp_server_identifier=%s\n' "${LEASE_SERVER:-192.0.2.10}" ;;
  -n) [ "${FAIL_REGEN:-0}" = 1 ] && exit 0
      { echo "# Generated by dhcpcd from wlan0.dhcp"; cat "$DEV/data/resolv.conf.head"; echo "nameserver 127.0.0.1"; echo "# tail"; } > "$DEV/tmp/resolv.conf" ;;
esac
SH
chmod +x "$T/bin/adb" "$T/bin/dev"/*

reset_device() {
  rm -f "$DEV"/data/resolv.conf.head.pre-front-* "$DEV/etc/resolv.conf.head" "$DEV/etc/resolv.conf" "$DEV/tmp/resolv.conf"
  printf 'nameserver 192.0.2.20\n' > "$DEV/data/resolv.conf.head"
  ln -s /data/resolv.conf.head "$DEV/etc/resolv.conf.head"
  ln -s ../tmp/resolv.conf "$DEV/etc/resolv.conf"
  { echo "# Generated by dhcpcd from wlan0.dhcp"; cat "$DEV/data/resolv.conf.head"; echo "nameserver 127.0.0.1"; echo "# tail"; } > "$DEV/tmp/resolv.conf"
}
reset_device

sed -e "s|^AISIS_LAN_DHCP_HOSTS_FILE=.*|AISIS_LAN_DHCP_HOSTS_FILE=$lan/config/dhcp-hosts.example.conf|" "$lan/config/lan.env.example" > "$T/lan.env"
chmod 600 "$T/lan.env"
export AISIS_LAN_ENV=$T/lan.env PATH=$T/bin:$PATH AISIS_SPEAKER_WAIT_S=2
S=$lan/speaker/speaker-dns.sh
sum_head() { cat "$DEV/data/resolv.conf.head"; }

plan=$(bash "$S" plan 2>&1)
check "plan prints the steps" "$(printf '%s\n' "$plan" | grep -c 'PLAN (nothing changed)')" 1
check "plan changes nothing" "$(sum_head)" "nameserver 192.0.2.20"
check "plan shows the checks" "$(printf '%s\n' "$plan" | grep -c 'lease server is the front')" 1

bash "$S" apply >"$T/apply.log" 2>&1 || { cat "$T/apply.log"; fail=1; }
check "head file is exactly one line with the resolver" "$(sum_head)" "nameserver 192.0.2.10"
check "a backup of the old head exists" "$(cat "$DEV"/data/resolv.conf.head.pre-front-* | head -n1)" "nameserver 192.0.2.20"
check "resolv.conf lists the resolver first" "$(sed -n 's/^nameserver //p' "$DEV/tmp/resolv.conf" | head -n1)" 192.0.2.10
check "the old resolver is gone from resolv.conf" "$(grep -c '192.0.2.20' "$DEV/tmp/resolv.conf")" 0
check "apply prints the undo command" "$(grep -c 'undo: .*undo --backup /data/resolv.conf.head.pre-front-' "$T/apply.log")" 1

second=$(bash "$S" apply 2>&1 || true)
check "a second apply is a no-op" "$(printf '%s\n' "$second" | grep -c 'nothing to do')" 1
check "a second apply makes no second backup" "$(find "$DEV/data" -name 'resolv.conf.head.pre-front-*' | wc -l | tr -d ' ')" 1
bash "$S" undo >"$T/undo.log" 2>&1 || { cat "$T/undo.log"; fail=1; }
check "undo restores the old head" "$(sum_head)" "nameserver 192.0.2.20"
check "undo regenerates resolv.conf" "$(sed -n 's/^nameserver //p' "$DEV/tmp/resolv.conf" | head -n1)" 192.0.2.20

reset_device
printf '# comments only, no nameserver\n' > "$DEV/data/resolv.conf.head"
bash "$S" apply >"$T/apply2.log" 2>&1 || { cat "$T/apply2.log"; fail=1; }
bash "$S" undo >"$T/undo2.log" 2>&1 || { cat "$T/undo2.log"; fail=1; }
check "undo restores a head file that had no nameserver line" "$(sum_head)" "# comments only, no nameserver"
check "undo says so" "$(grep -c 'no nameserver line' "$T/undo2.log")" 1

check "undo refuses a backup name with shell metacharacters" "$(bash "$S" undo --backup '/data/resolv.conf.head.pre-front-20260101-000000; id' 2>&1 | grep -c 'backup must look like')" 1
# failed verification (the resolver file never regenerates) reverts by itself and exits non-zero
reset_device
if FAIL_REGEN=1 bash "$S" apply >"$T/revert.log" 2>&1; then rc=0; else rc=$?; fi
check "failed verification exits non-zero" "$([ "$rc" -ne 0 ] && echo yes)" yes
check "failed verification restores the old head" "$(sum_head)" "nameserver 192.0.2.20"

# preflight refusals change nothing
reset_device
check "lease from another server is refused" "$(LEASE_SERVER=192.0.2.99 bash "$S" apply 2>&1 | grep -c 'move DHCP first')" 1
check "no change after that refusal" "$(sum_head)" "nameserver 192.0.2.20"
check "resolver that does not override is refused" "$(CANARY_ANSWER=198.51.100.7 bash "$S" apply 2>&1 | grep -c 'override is off or unreachable')" 1
check "no change after that refusal too" "$(sum_head)" "nameserver 192.0.2.20"
rm "$DEV/etc/resolv.conf.head"; ln -s /somewhere/else "$DEV/etc/resolv.conf.head"
check "a changed pinning mechanism is refused" "$(bash "$S" apply 2>&1 | grep -c 'mechanism changed')" 1
check "no change after the mechanism refusal" "$(sum_head)" "nameserver 192.0.2.20"
exit "$fail"
